    private void accionCrearArbol() {
        arbol = new ArbolBST();
        txtSalida.setText("Árbol Binario de Búsqueda inicializado correctamente.\n");
    }

    private void accionAgregar() {
        try {
            if (txtId.getText().trim().isEmpty() || txtNombre.getText().trim().isEmpty() ||
                txtPuesto.getText().trim().isEmpty() || txtDepartamento.getText().trim().isEmpty() ||
                txtSalario.getText().trim().isEmpty()) {
                txtSalida.setText("Error: Todos los campos de texto son obligatorios para agregar.\n");
                return;
            }

            Integer id = Integer.parseInt(txtId.getText().trim());
            String nombre = txtNombre.getText().trim();
            String puesto = txtPuesto.getText().trim();
            String depto = txtDepartamento.getText().trim();
            Double salario = Double.parseDouble(txtSalario.getText().trim());

            Empleado nuevo = new Empleado(id, nombre, puesto, depto, salario);
            arbol.insertar(nuevo);
            txtSalida.setText("Empleado agregado exitosamente:\n" + nuevo.toString() + "\n");
            limpiarCampos();
        } catch (NumberFormatException e) {
            txtSalida.setText("Error: El ID debe ser un entero y el Salario un número válido.\n");
        } catch (IllegalArgumentException e) {
            txtSalida.setText("Error de validación: " + e.getMessage() + "\n");
        }
    }

    private void accionBuscar() {
        try {
            if (txtId.getText().trim().isEmpty()) {
                txtSalida.setText("Ingrese un ID en el campo 'ID' para buscar.\n");
                return;
            }
            Integer id = Integer.parseInt(txtId.getText().trim());
            Empleado emp = arbol.buscar(id);
            if (emp != null) {
                txtSalida.setText("Empleado Encontrado:\n" + emp.toString() + "\n");
            } else {
                txtSalida.setText("No se encontró ningún empleado con el ID: " + id + "\n");
            }
        } catch (NumberFormatException e) {
            txtSalida.setText("Error: Ingrese un ID numérico válido para buscar.\n");
        }
    }

    private void accionEliminar() {
        try {
            if (txtId.getText().trim().isEmpty()) {
                txtSalida.setText("Ingrese un ID en el campo 'ID' para eliminar.\n");
                return;
            }
            Integer id = Integer.parseInt(txtId.getText().trim());
            boolean eliminado = arbol.eliminar(id);
            if (eliminado) {
                txtSalida.setText("Empleado con ID " + id + " eliminado correctamente.\n");
                limpiarCampos();
            } else {
                txtSalida.setText("No se pudo eliminar. El ID " + id + " no existe en el árbol.\n");
            }
        } catch (NumberFormatException e) {
            txtSalida.setText("Error: Ingrese un ID numérico válido para eliminar.\n");
        }
    }

    private void accionInOrden() {
        mostrarLista("RECORRIDO INORDEN (Ordenado por ID)", arbol.mostrarInOrden());
    }

    private void accionPreOrden() {
        mostrarLista("RECORRIDO PREORDEN", arbol.mostrarPreOrden());
    }

    private void accionPostOrden() {
        mostrarLista("RECORRIDO POSTORDEN", arbol.mostrarPostOrden());
    }

    private void mostrarLista(String titulo, java.util.List<Empleado> lista) {
        if (lista.isEmpty()) {
            txtSalida.setText(titulo + ":\nEl árbol está vacío.\n");
            return;
        }
        StringBuilder sb = new StringBuilder("=== " + titulo + " ===\n");
        for (Empleado emp : lista) {
            sb.append(emp.toString()).append("\n");
        }
        txtSalida.setText(sb.toString());
    }

    private void accionAmplitud() {
        txtSalida.setText("Amplitud del árbol (máximo número de nodos en un nivel): " + arbol.amplitud() + "\n");
    }

    private void accionProfundidad() {
        txtSalida.setText("Profundidad / Altura del árbol: " + arbol.profundidad() + " niveles.\n");
    }

    private void accionBalancear() {
        arbol.balancear();
        txtSalida.setText("El árbol ha sido reestructurado y balanceado exitosamente.\n");
    }

    private void accionDestruir() {
        arbol.destruirArbol();
        txtSalida.setText("Árbol destruido. La raíz ha sido establecida en null.\n");
        limpiarCampos();
    }

    private void limpiarCampos() {
        txtId.setText("");
        txtNombre.setText("");
        txtPuesto.setText("");
        txtDepartamento.setText("");
        txtSalario.setText("");
    }
